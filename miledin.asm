; miledin.asm — Синее предзагрузочное меню диагностики MidenOS (32-bit Pre-Boot Menu)
[BITS 32]

miledin_entry:
    cli
    cld
    mov byte [m_menu_sel], 0

    ; Проверяем наличие графического Linear Framebuffer
    mov eax, [m_fb_addr]
    test eax, eax
    jz .vga_menu

.gfx_redraw:
    ; 1. Заливаем фон классическим глубоким синим цветом (#003377)
    mov edi, [m_fb_addr]
    mov ebx, [m_fb_height]
    test ebx, ebx
    jnz .h_ok
    mov ebx, 768
.h_ok:
    mov edx, [m_fb_width]
    test edx, edx
    jnz .w_ok
    mov edx, 1024
.w_ok:
    mov esi, [m_fb_pitch]
    test esi, esi
    jnz .p_ok
    mov esi, edx
    shl esi, 2
.p_ok:
    mov [m_scr_w], edx
    mov [m_scr_h], ebx
    mov [m_scr_p], esi

.cls_y:
    push edi
    mov ecx, edx
    mov eax, 0x00003377
    rep stosd
    pop edi
    add edi, esi
    dec ebx
    jnz .cls_y

    ; 2. Верхняя светло-синяя шапка (#0066CC, высота 48 px)
    mov edi, [m_fb_addr]
    mov ebx, 48
.hdr_y:
    push edi
    mov ecx, [m_scr_w]
    mov eax, 0x000066CC
    rep stosd
    pop edi
    add edi, [m_scr_p]
    dec ebx
    jnz .hdr_y

    ; Заголовок в шапке
    mov esi, txt_header
    mov ebx, 32
    mov edx, 16
    mov eax, 0x00FFFFFF
    call m_draw_str

    ; 3. Центральное окно меню (X=212, Y=160, W=600, H=340, фон #004499)
    mov edi, [m_fb_addr]
    mov eax, 160
    imul eax, [m_scr_p]
    add edi, eax
    add edi, 212 * 4
    mov ebx, 340
.win_y:
    push edi
    mov ecx, 600
    mov eax, 0x00004499
    rep stosd
    pop edi
    add edi, [m_scr_p]
    dec ebx
    jnz .win_y

    ; Рамка вокруг окна меню
    mov edi, [m_fb_addr]
    mov eax, 160
    imul eax, [m_scr_p]
    add edi, eax
    add edi, 212 * 4
    mov ecx, 600
    mov eax, 0x0066B2FF
    rep stosd

    mov edi, [m_fb_addr]
    mov eax, 499
    imul eax, [m_scr_p]
    add edi, eax
    add edi, 212 * 4
    mov ecx, 600
    mov eax, 0x0066B2FF
    rep stosd

    mov esi, txt_title
    mov ebx, 240
    mov edx, 185
    mov eax, 0x0066CCFF
    call m_draw_str

    ; 4. Пункты меню (0: Запуск MidenOS, 1: Установка системы, 2: Перезагрузка)
    ; Пункт 0
    mov al, [m_menu_sel]
    cmp al, 0
    jne .item0_norm
    mov ebx, 232
    mov edx, 235
    mov ecx, 560
    mov edi, 32
    mov eax, 0x000078D4
    call m_fill_rect
.item0_norm:
    mov esi, txt_item0
    mov ebx, 248
    mov edx, 243
    mov eax, 0x00FFFFFF
    call m_draw_str

    ; Пункт 1
    mov al, [m_menu_sel]
    cmp al, 1
    jne .item1_norm
    mov ebx, 232
    mov edx, 280
    mov ecx, 560
    mov edi, 32
    mov eax, 0x000078D4
    call m_fill_rect
.item1_norm:
    mov esi, txt_item1
    mov ebx, 248
    mov edx, 288
    mov eax, 0x00FFFFFF
    call m_draw_str

    ; Пункт 2
    mov al, [m_menu_sel]
    cmp al, 2
    jne .item2_norm
    mov ebx, 232
    mov edx, 325
    mov ecx, 560
    mov edi, 32
    mov eax, 0x000078D4
    call m_fill_rect
.item2_norm:
    mov esi, txt_item2
    mov ebx, 248
    mov edx, 333
    mov eax, 0x00FFFFFF
    call m_draw_str

    ; Подсказка внизу окна
    mov esi, txt_hint
    mov ebx, 240
    mov edx, 455
    mov eax, 0x00AACCFF
    call m_draw_str

    ; 5. Опрос клавиатуры PS/2
.gfx_key_loop:
    in al, 0x64
    test al, 1
    jz .gfx_key_loop
    in al, 0x60
    test al, 0x80
    jnz .gfx_key_loop               ; Игнорируем отпускание клавиши

    cmp al, 0x48                    ; Стрелка ВВЕРХ
    je .key_up
    cmp al, 0x50                    ; Стрелка ВНИЗ
    je .key_down
    cmp al, 0x1C                    ; ENTER
    je .key_enter
    cmp al, 0x01                    ; ESC
    je .boot_normal
    jmp .gfx_key_loop

.key_up:
    mov al, [m_menu_sel]
    test al, al
    jz .gfx_redraw
    dec byte [m_menu_sel]
    jmp .gfx_redraw

.key_down:
    mov al, [m_menu_sel]
    cmp al, 2
    jge .gfx_redraw
    inc byte [m_menu_sel]
    jmp .gfx_redraw

.key_enter:
    mov al, [m_menu_sel]
    cmp al, 0
    je .boot_normal
    cmp al, 1
    je .boot_install
    ; Пункт 2 — Перезагрузка ПК
    mov al, 0xFE
    out 0x64, al
    hlt

.boot_install:
    mov byte [m_install_flag], 1
    jmp miledin_done_to_os

.boot_normal:
    mov byte [m_install_flag], 0
    jmp miledin_done_to_os

; Резервное синее меню в текстовом режиме VGA 0xB8000 (если VBE не включён)
.vga_menu:
    mov edi, 0x000B8000
    mov ecx, 80 * 25
    mov ax, 0x1F20
    rep stosw
    mov edi, 0x000B8000 + 160 * 4 + 16
    mov esi, txt_header
    mov ah, 0x1F
.vga_pr:
    lodsb
    test al, al
    jz .vga_wait
    stosw
    jmp .vga_pr
.vga_wait:
    in al, 0x64
    test al, 1
    jz .vga_wait
    in al, 0x60
    cmp al, 0x1C
    je .boot_normal
    jmp .vga_wait

; Вспомогательная заливка прямоугольника: EBX=X, EDX=Y, ECX=W, EDI=H, EAX=Color
m_fill_rect:
    push ebp
    mov ebp, eax
    mov eax, edx
    imul eax, [m_scr_p]
    add eax, [m_fb_addr]
    shl ebx, 2
    add eax, ebx
    mov edx, eax
.fr_ly:
    push edx
    push ecx
    mov eax, ebp
    push edi
    mov edi, edx
    rep stosd
    pop edi
    pop ecx
    pop edx
    add edx, [m_scr_p]
    dec edi
    jnz .fr_ly
    pop ebp
    ret

; Вывод ASCII-строки (масштаб 2x): ESI=str, EBX=X, EDX=Y, EAX=Color
m_draw_str:
    pushad
    mov [m_txt_col], eax
.str_next:
    lodsb
    test al, al
    jz .str_done
    cmp al, 32
    jl .str_adv
    cmp al, 126
    jg .str_adv
    sub al, 32
    movzx eax, al
    shl eax, 3
    lea ebp, [m_font8x8 + eax]

    xor ecx, ecx                    ; row 0..7
.glyph_row:
    cmp ecx, 8
    jge .str_adv
    mov al, [ebp + ecx]
    push ecx
    push ebx

    ; Y на экране = EDX + ecx * 2
    mov edi, ecx
    shl edi, 1
    add edi, edx
    imul edi, [m_scr_p]
    add edi, [m_fb_addr]
    mov eax, ebx
    shl eax, 2
    add edi, eax

    mov cl, 8
.glyph_bit:
    pop ebx
    pop eax
    push eax
    push ebx
    mov ah, [ebp + eax]
    push ecx
    mov cl, [esp]
    dec cl
    shr ah, cl
    test ah, 1
    jz .no_px
    mov eax, [m_txt_col]
    mov [edi], eax
    mov [edi + 4], eax
    push edi
    add edi, [m_scr_p]
    mov [edi], eax
    mov [edi + 4], eax
    pop edi
.no_px:
    add edi, 8
    pop ecx
    dec cl
    jnz .glyph_bit

    pop ebx
    pop ecx
    inc ecx
    jmp .glyph_row

.str_adv:
    add ebx, 18
    jmp .str_next
.str_done:
    popad
    ret

m_menu_sel: db 0
m_scr_w:    dd 1024
m_scr_h:    dd 768
m_scr_p:    dd 4096
